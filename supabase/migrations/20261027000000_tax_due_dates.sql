-- Calendario de vencimientos: día del mes de cada impuesto según el último dígito del CUIT.
-- Se carga y edita desde la sección Vencimientos; el Resumen lo cruza con los clientes.
create table if not exists public.tax_due_dates (
  year int not null check (year between 2000 and 2100),
  month int not null check (month between 1 and 12),
  tax text not null check (tax in ('autonomo', 'muni', 'iibb', 'cm', 'iva', 'sicore')),
  digit int not null check (digit between 0 and 9),
  day int not null check (day between 1 and 31),
  updated_by uuid references auth.users(id) default auth.uid(),
  updated_at timestamptz not null default now(),
  primary key (year, month, tax, digit)
);

alter table public.tax_due_dates enable row level security;

create policy "Authenticated users can manage tax due dates"
  on public.tax_due_dates for all to authenticated
  using (true) with check (true);

